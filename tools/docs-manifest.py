#!/usr/bin/env python3
"""Generate docs/MANIFEST.md: what each captured document is, and a digest.

The provenance is in the filename, which was written by the fetch step:

    docs/cf/br/quick-actions.md         -> developers.cloudflare.com/browser-run/quick-actions/
    docs/cf/br/quick-actions__pdf-endpoint.md -> .../browser-run/quick-actions/pdf-endpoint/
    docs/cf2/workers_platform_pricing.md -> developers.cloudflare.com/workers/platform/pricing/
    docs/other/jina.ai_reader.html      -> jina.ai/reader
    docs/mkt/cwpbr.html                 -> cloudflare.com/products/browser-run/

The title is read back out of the capture itself rather than reconstructed, so a
file that is not what its name claims shows up as a disagreement.
"""
import hashlib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"


def title_of(path: pathlib.Path) -> str:
    raw = path.read_text(encoding="utf8", errors="replace")
    if path.suffix == ".md":
        m = re.search(r"^title:\s*(.+)$", raw, re.M)
        if m:
            return m.group(1).strip()
        m = re.search(r"^#\s+(.+)$", raw, re.M)
        if m:
            return m.group(1).strip()
    elif path.suffix == ".html":
        m = re.search(r"<title>(.*?)</title>", raw, re.S)
        if m:
            return re.sub(r"\s+", " ", m.group(1)).strip()
    for line in raw.splitlines():
        if line.strip() and line.strip() not in ("---",):
            return re.sub(r"\s+", " ", line.strip())[:80]
    return "(empty)"


CF2_SOURCES = {
    "turnstile.md": "developers.cloudflare.com/turnstile/",
    "turnstile_get-started_server-side-validation.md":
        "developers.cloudflare.com/turnstile/get-started/server-side-validation/",
    "wai_pricing.md": "developers.cloudflare.com/workers-ai/platform/pricing/",
    "workers-ai_models.md": "developers.cloudflare.com/workers-ai/models/",
    "workers_platform_limits.md": "developers.cloudflare.com/workers/platform/limits/",
    "workers_platform_pricing.md": "developers.cloudflare.com/workers/platform/pricing/",
    "workers_runtime-apis_tcp-sockets.md":
        "developers.cloudflare.com/workers/runtime-apis/tcp-sockets/",
}

MKT_SOURCES = {
    "cwpbr.html": "cloudflare.com/products/browser-run/",
}


def source_of(rel: str) -> str:
    p = rel.split("/")[1:]          # drop the leading "docs/"
    if p[:2] == ["cf", "br"]:
        rest = re.sub(r"\.md$", "", "/".join(p[2:])).replace("__", "/")
        return "developers.cloudflare.com/browser-run/" if rest == "index" \
            else f"developers.cloudflare.com/browser-run/{rest}/"
    if p[0] == "cf2":
        return CF2_SOURCES.get(p[1], "developers.cloudflare.com — " + p[1])
    if p[0] == "mkt":
        return MKT_SOURCES.get(p[1], "cloudflare.com — " + p[1])
    if p[0] == "cf":
        if p[1] == "br_llms.txt":
            return "developers.cloudflare.com/browser-run/llms.txt"
        rest = re.sub(r"\.(html|txt)$", "", p[1]).replace("_", "/")
        return f"developers.cloudflare.com/{rest}/"
    if p[0] == "other":
        name = re.sub(r"\.(md|html|txt)$", "", p[1])
        suffix = pathlib.Path(p[1]).suffix
        if "_" not in name:
            return name + suffix
        domain, rest = name.split("_", 1)
        rest = rest.replace("__", "/").replace("_", "/")
        if rest == "llms":
            return f"{domain}/llms.txt"
        return f"{domain}/{rest}/"
    if p[0] == "rfc8448.txt":
        return "rfc-editor.org/rfc/rfc8448.txt"
    return "local (not fetched)"


def main() -> int:
    rows = []
    for path in sorted(DOCS.rglob("*")):
        if not path.is_file() or path.name == "MANIFEST.md":
            continue
        rel = path.relative_to(ROOT).as_posix()
        digest = hashlib.sha256(path.read_bytes()).hexdigest()[:16]
        rows.append((rel, str(path.stat().st_size), digest, source_of(rel), title_of(path)))

    out = [
        "# Captured-document manifest",
        "",
        "Generated by `python3 tools/docs-manifest.py`. Everything under `docs/` was",
        "captured on 2026-10-13. The digest is the first 16 hex characters of the",
        "SHA-256 of the file as shipped, so a quote can be tied to an exact capture.",
        "",
        "Fetches that returned a 404 notice, exact duplicates, and superseded shorter",
        "captures were removed rather than shipped; the surviving set has no duplicate",
        "content and no error pages.",
        "",
        f"{len(rows)} files.",
        "",
        "| file | bytes | sha256/16 | source | title |",
        "| --- | ---: | --- | --- | --- |",
    ]
    for rel, size, digest, source, title in rows:
        title = title.replace("|", r"\|")
        out.append(f"| `{rel}` | {size} | `{digest}` | {source} | {title} |")
    out.append("")

    (DOCS / "MANIFEST.md").write_text("\n".join(out), encoding="utf8")
    print(f"wrote {DOCS / 'MANIFEST.md'} ({len(rows)} files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
